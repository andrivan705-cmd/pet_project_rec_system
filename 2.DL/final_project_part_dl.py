from torch.utils.data import Dataset # пустой шаблон
from torch.utils.data import DataLoader # хранит батчи
from transformers import DataCollatorWithPadding # автоматический упаковщик до максимальной длины одного из постов (добавляет нули к коротким текстам внутри одной пачки)


# Создаём хранилище, внутри которого прописываем правила для работы с данными
class PostDataset(Dataset):
    def __init__(self, texts, tokenizer): # подготовка при создании
        super().__init__() # запускает настройки родительского класса Dataset

        self.texts = tokenizer( # токенизатор для обратбоки целого списка текстов
            texts, # наши сырые тексты
            add_special_tokens=True, # служебные маркеры начала и конца текста специально для моделей BERT семейства
            return_token_type_ids=False, # отключает маски типов токенов (для наших постов она не нужна, только для пару предложений)
            return_tensors='pt', # возвращает результат в виде готовых тензоров матриц
            truncation=True, # умная обрезка текстов (обычно 512 токенов), защита от критической ошибки
            padding=True # предварительное выравнивание
        )
        self.tokenizer = tokenizer # записываем объект токенизатора во внутреннюю память класса

    def __getitem__(self, idx): # этот метод учить программу вовзращать две пары ключ-значение
        return {
            'input_ids': self.texts['input_ids'][idx], # зашифрованный текст поста
            'attention_mask': self.texts['attention_mask'][idx] # карта-подсказка для нейросети, которая содержит важность(вес) каждого слова в посте
            }

    def __len__(self):
        return len(self.texts['input_ids']) # общее количество постов в нашем наборе данных


