def get_model(model_name):
    assert model_name in ['bert', 'roberta', 'distilbert'] # проверяем, есть ли переданное имя нейросети среди этих моделей

    # создаем словарь, ключ - имя нейросети, значение - чекпоинт нейросети
    checkpoint_names = {
        'bert': 'bert-base-cased',  # https://huggingface.co/bert-base-cased
        'roberta': 'roberta-base',  # https://huggingface.co/roberta-base
        'distilbert': 'distilbert-base-cased'  # https://huggingface.co/distilbert-base-cased
    }
    # создаем словарь, ключ - имя нейросети, значение - чекпоинт нейросети
    model_classes = {
        'bert': BertModel,
        'roberta': RobertaModel,
        'distilbert': DistilBertModel
    }

    # возвращаем токенизатор через чекпоинт нейросети, саму модель через чекпоинт нейросети
    return AutoTokenizer.from_pretrained(checkpoint_names[model_name]), model_classes[model_name].from_pretrained(checkpoint_names[model_name])

