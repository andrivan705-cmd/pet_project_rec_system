### Пытаемся кластеризовать тексты

from sklearn.decomposition import PCA # метод главных компонент - ищет скрытые связи и схлопывает сотни признаков в дестяки информативных

centered = embeddings - embeddings.mean() # из каждого числа в в матрице вычитается среднее из всей матрицы

pca = PCA(n_components=50) # ужимаем размер эмбеддинга с 768 чисел до 50
pca_decomp = pca.fit_transform(centered) # трансформация матрицы centered

from sklearn.cluster import KMeans # импортиркем алгоритм ближайших соседей

n_clusters = 15 # задаем количество кластеров

# создаем объект алгоритма, random_state=0 нужен для того, чтобы при каждом перезапуске ячейки посты делились на группы абсолютно одинаково
#.fit(pca_decomp) запускает процесс кластеризации
kmeans = KMeans(n_clusters=n_clusters, random_state=0).fit(pca_decomp)

# в таблице постов создается новая колонка 'TextCluster', у которой значение соответствует номеру кластера для каждого поста
posts_info['TextCluster'] = kmeans.labels_

# создаем будущие колонки таблицы постов с номера кластеров 'DistanceToCluster_0', 'DistanceToCluster_1', ...,
dists_columns = [f'DistanceToCluster_{i}' for i in range(n_clusters)]

#
dists_df = pd.DataFrame( # наша новая таблица расстояний (вместо самих номеров кластеров)
    data=kmeans.transform(pca_decomp), # этот метод считает физическое расстояние от каждого поста до центра каждого кластера
    columns=dists_columns # созданные выше колонки
)

