import torch # импорт библиотеки PyTorch
from tqdm import tqdm # импорт визуального индикатора прогресса


@torch.inference_mode() # заморозка нейросети (отключение вычиссления градиентов)
def get_embeddings_labels(model, loader): # принимаем на вход функции саму модель и подготовленный конвейер данных
    model.eval() # переводим в режим оценки нашу модель

    total_embeddings = [] # список с эмбеддингами

    for batch in tqdm(loader): # tqdm берет конвейер и начинает выдавать из него данные пачками по 32 поста за раз
        batch = {key: batch[key].to(device) for key in ['attention_mask', 'input_ids']} # переносит данные из оперативной памяти компьютера в память видеокарты

        embeddings = model(**batch)['last_hidden_state'][:, 0, :]
        # model(**batch) - здесь мы распаковываем словарь батч, в котором есть две коробки: 'attention_mask', 'input_ids'
        # ['last_hidden_state'] - здесь мы по ключу достаем матрицу (последнее скрытое состояние) - выход из последнего слоя нейросети
        # [:, 0, :] - : - взять абсолютно все посты, 0 - из каждого поста берем только первое слово (служебный маркер CLS, в котором заложен контекст всего поста), : - взять все 768 чисел характеристики для токена CLS
        total_embeddings.append(embeddings.cpu()) # соответственно добавляем готовые эмбеддинги в список с эмбеддингами с ЦПУ

    return torch.cat(total_embeddings, dim=0) # берем и склеиваем все наши эмбеддинги со всех батчей по вертикали

device = torch.device('cuda:0' if torch.cuda.is_available() else 'cpu')

